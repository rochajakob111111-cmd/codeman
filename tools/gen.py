"""Generate code from the sheets: one struct per row. Run: python3 tools/gen.py"""
import sys

from sheets import ROOT, all_sheets

HDR = "// GENERATED by tools/gen.py from sheets/{src}. Edit the sheet, not this file.\n"
JPKG = "gg.craftblade.gen"
JDIR = "fabric/src/main/java/gg/craftblade/gen"
CDIR = "bas/src/Gen"

JT = {"u8": "int", "i32": "int", "f32": "float", "f64": "double", "str": "String", "bytes": "byte[]"}
JW = {"u8": "o.writeByte({v})", "i32": "o.writeInt({v})", "f32": "o.writeFloat({v})", "f64": "o.writeDouble({v})",
      "str": "o.writeUTF({v})", "bytes": "o.writeInt({v}.length); o.write({v})"}
JR = {"u8": "i.readUnsignedByte()", "i32": "i.readInt()", "f32": "i.readFloat()", "f64": "i.readDouble()",
      "str": "i.readUTF()", "bytes": "readBytes(i)"}
CT = {"u8": "byte", "i32": "int", "f32": "float", "f64": "double", "str": "string", "bytes": "byte[]"}
CW = {"u8": "w.U8({v})", "i32": "w.I32({v})", "f32": "w.F32({v})", "f64": "w.F64({v})", "str": "w.Str({v})", "bytes": "w.Bytes({v})"}
CR = {"u8": "r.U8()", "i32": "r.I32()", "f32": "r.F32()", "f64": "r.F64()", "str": "r.Str()", "bytes": "r.Bytes()"}


def fields(row):
    return [tuple(f.split(":")) for f in row["fields"]]


def java_msg(p):
    out = [HDR.format(src="protocol.json"), f"package {JPKG};\n",
           "import java.io.*;\n",
           "public sealed interface Msg permits " + ", ".join(f"Msg.{r['name']}" for r in p["rows"]) + " {",
           f"    int PROTOCOL = {len(p['rows'])};",
           "    int id();",
           "    void write(DataOutputStream o) throws IOException;", ""]
    for r in p["rows"]:
        fs = fields(r)
        params = ", ".join(f"{JT[t]} {n}" for n, t in fs)
        out.append(f"    /** {r['purpose']} ({r['direction']}, {r['rate']}) */")
        out.append(f"    record {r['name']}({params}) implements Msg {{")
        out.append(f"        public static final int ID = {r['id']};")
        out.append(f"        public int id() {{ return ID; }}")
        out.append("        public void write(DataOutputStream o) throws IOException {")
        for n, t in fs:
            out.append("            " + JW[t].format(v=n) + ";")
        out.append("        }")
        args = ", ".join(JR[t] for _, t in fs)
        out.append(f"        static {r['name']} read(DataInputStream i) throws IOException {{ return new {r['name']}({args}); }}")
        out.append("    }\n")
    out.append("    static Msg read(int id, DataInputStream i) throws IOException {")
    out.append("        return switch (id) {")
    for r in p["rows"]:
        out.append(f"            case {r['id']} -> {r['name']}.read(i);")
    out.append('            default -> throw new IOException("unknown message id " + id);')
    out.append("        };")
    out.append("    }\n")
    out.append("    private static byte[] readBytes(DataInputStream i) throws IOException {")
    out.append("        int n = i.readInt();")
    out.append('        if (n < 0 || n > (64 << 20)) throw new IOException("bad length " + n);')
    out.append("        byte[] b = new byte[n]; i.readFully(b); return b;")
    out.append("    }")
    out.append("}")
    return "\n".join(out) + "\n"


def cs_msg(p):
    out = [HDR.format(src="protocol.json"), "namespace CraftBlade.Gen", "{",
           "    public abstract class Msg", "    {",
           f"        public const int PROTOCOL = {len(p['rows'])};",
           "        public abstract int Id { get; }",
           "        public abstract void Write(Wire.Writer w);", ""]
    out.append("        public static Msg Read(int id, Wire.Reader r)")
    out.append("        {")
    out.append("            switch (id)")
    out.append("            {")
    for r in p["rows"]:
        out.append(f"                case {r['id']}: return {r['name']}.Read(r);")
    out.append('                default: throw new System.IO.IOException("unknown message id " + id);')
    out.append("            }")
    out.append("        }")
    out.append("    }\n")
    for r in p["rows"]:
        fs = fields(r)
        out.append(f"    /// <summary>{r['purpose']} ({r['direction']}, {r['rate']})</summary>")
        out.append(f"    public sealed class {r['name']} : Msg")
        out.append("    {")
        out.append(f"        public const int ID = {r['id']};")
        out.append("        public override int Id { get { return ID; } }")
        for n, t in fs:
            out.append(f"        public {CT[t]} {n};")
        out.append("        public override void Write(Wire.Writer w)")
        out.append("        {")
        for n, t in fs:
            out.append("            " + CW[t].format(v=n) + ";")
        out.append("        }")
        out.append(f"        public static {r['name']} Read(Wire.Reader r)")
        out.append("        {")
        out.append(f"            var m = new {r['name']}();")
        for n, t in fs:
            out.append(f"            m.{n} = {CR[t]};")
        out.append("            return m;")
        out.append("        }")
        out.append("    }\n")
    out.append("}")
    return "\n".join(out) + "\n"


def java_tables(s):
    shapes = s["shapes"]["rows"]
    dmg = s["damage"]["rows"]
    cfg = [r for r in s["config"]["rows"] if r["side"] in ("mc", "both")]
    jt = {"int": "int", "double": "double", "float": "float", "string": "String"}
    out = [HDR.format(src="shapes.json, damage.json, config.json"), f"package {JPKG};\n",
           "public final class Tables {", "    private Tables() {}", ""]
    out.append("    // shapes.json")
    for r in shapes:
        out.append(f"    public static final int SHAPE_{r['name'].upper()} = {r['id']};")
    out.append("\n    // damage.json")
    out.append("    public record Damage(int id, String basType, float scale, float minSpeed, float maxMc, float knockbackPerMs) {}")
    out.append("    public static final Damage[] DAMAGE = {")
    for r in dmg:
        out.append(f"        new Damage({r['id']}, \"{r['basType']}\", {r['scale']}f, {r['minSpeed']}f, {r['maxMc']}f, {r['knockbackPerMs']}f),")
    out.append("    };")
    out.append("\n    // config.json (defaults)")
    for r in cfg:
        v = f"\"{r['default']}\"" if r["type"] == "string" else r["default"] + ("f" if r["type"] == "float" else "")
        out.append(f"    /** {r['purpose']} */")
        out.append(f"    public static final {jt[r['type']]} DEFAULT_{snake(r['key'])} = {v};")
    out.append("}")
    return "\n".join(out) + "\n"


def cs_tables(s):
    shapes = s["shapes"]["rows"]
    dmg = s["damage"]["rows"]
    ents = s["entities"]["rows"]
    cfg = [r for r in s["config"]["rows"] if r["side"] in ("bas", "both")]
    ct = {"int": "int", "double": "double", "float": "float", "string": "string"}
    out = [HDR.format(src="shapes.json, damage.json, entities.json, config.json"),
           "namespace CraftBlade.Gen", "{", "    public static class Tables", "    {"]
    out.append("        // shapes.json")
    for r in shapes:
        out.append(f"        public const int SHAPE_{r['name'].upper()} = {r['id']};")
    out.append("\n        // damage.json: B&S DamageType name -> wire id")
    out.append("        public static int DamageId(string basType)")
    out.append("        {")
    out.append("            switch (basType)")
    out.append("            {")
    for r in dmg:
        out.append(f"                case \"{r['basType']}\": return {r['id']};")
    out.append("                default: return 0;")
    out.append("            }")
    out.append("        }")
    out.append("        public static readonly float[] DamageMinSpeed = { " + ", ".join(f"{r['minSpeed']}f" for r in dmg) + " };")
    out.append("\n        // entities.json")
    out.append("        public struct EntityRule { public string mcType; public bool creature; public string basCreature; }")
    out.append("        public static readonly EntityRule[] Entities =")
    out.append("        {")
    for r in ents:
        out.append(f"            new EntityRule {{ mcType = \"{r['mcType']}\", creature = {str(r['representation'] == 'creature').lower()}, basCreature = \"{r['basCreature']}\" }},")
    out.append("        };")
    out.append("\n        // config.json (defaults)")
    for r in cfg:
        v = f"\"{r['default']}\"" if r["type"] == "string" else r["default"] + ("f" if r["type"] == "float" else "")
        out.append(f"        /// <summary>{r['purpose']}</summary>")
        out.append(f"        public const {ct[r['type']]} DEFAULT_{snake(r['key'])} = {v};")
    out.append("    }")
    out.append("}")
    return "\n".join(out) + "\n"


def snake(k):
    return "".join("_" + c if c.isupper() else c.upper() for c in k)


def outputs(s):
    return {
        f"{JDIR}/Msg.java": java_msg(s["protocol"]),
        f"{JDIR}/Tables.java": java_tables(s),
        f"{CDIR}/Msg.cs": cs_msg(s["protocol"]),
        f"{CDIR}/Tables.cs": cs_tables(s),
    }


if __name__ == "__main__":
    for path, text in outputs(all_sheets()).items():
        p = ROOT / path
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8", newline="\n")
        print("wrote", path)
